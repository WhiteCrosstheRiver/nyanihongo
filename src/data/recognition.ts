const DOG_START = 151, DOG_END = 268;

export function labelToWord(index: number): Word | undefined {
  if (index >= DOG_START && index <= DOG_END) return findWord('いぬ', 'animals');
  const label = IMAGENET[index]?.toLowerCase() ?? '';
  for (const [re, kana, cat] of RULES) if (re.test(label)) return findWord(kana, cat);
  return undefined;
}

export const labelText = (index: number) => (IMAGENET[index] ?? '').split(',')[0];

/** How many of the 1000 model classes have a vocabulary match. */
export function coverage() {
  let n = 0;
  for (let i = 0; i < IMAGENET.length; i++) if (labelToWord(i)) n++;
  return n;
}
